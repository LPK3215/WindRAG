"""Generate the static data consumed by the project overview page.

The page is committed to GitHub Pages, while its measurable values come from
the generated index and evaluation reports. This script keeps those values in
one reproducible asset and supports a drift check for CI.

Usage:
    python scripts/visualization/generate_overview.py
    python scripts/visualization/generate_overview.py --check
"""

from __future__ import annotations

import argparse
import json
import re
import unittest
from pathlib import Path
from typing import Any, Dict, List


ROOT = Path(__file__).resolve().parents[2]
META_PATH = ROOT / "data" / "pure_index" / "meta.json"
REPORT_PATH = ROOT / "data" / "pure_index" / "report.json"
ABLATION_PATH = ROOT / "data" / "pure_index" / "ablation.json"
VERSION_PATH = ROOT / "src" / "pure_rag" / "__init__.py"
OUTPUT_PATH = ROOT / "docs" / "project_overview" / "overview-data.js"

BEGIN_MARKER = "/* BEGIN AUTO:OVERVIEW_DATA (generated by: python scripts/visualization/generate_overview.py) */"
END_MARKER = "/* END AUTO:OVERVIEW_DATA */"
ANSWER_LAYERS = ("qa_verbatim", "qa_rewrite", "fault_case", "doc_title")
LAYER_LABELS = {
    "qa_verbatim": "QA verbatim",
    "qa_rewrite": "QA rewrite",
    "fault_case": "Fault case",
    "doc_title": "Doc title",
    "near_miss": "Near-miss",
    "negative_ood": "Out-of-domain",
    "negative_missing": "Missing-material",
    "human_like": "Colloquial (human)",
}
ABLATION_LABELS = (
    "BM25 only",
    "TF-IDF only",
    "Hybrid alpha=0.7",
    "+ adaptive alpha",
    "+ synonyms",
    "+ query expand",
    "+ MMR rerank",
    "+ knowledge graph",
    "full - new-words",
)


def load_json(path: Path) -> Dict[str, Any]:
    if not path.exists():
        raise SystemExit(
            f"[overview] missing source file {path}; run `python src/simulate_corpus.py`, "
            "`python src/rag_cli.py build`, `python src/rag_cli.py eval --report`, "
            "and `python src/rag_cli.py ablation` first"
        )
    with path.open("r", encoding="utf-8") as handle:
        return json.load(handle)


def read_version() -> str:
    text = VERSION_PATH.read_text(encoding="utf-8")
    match = re.search(r'^__version__\s*=\s*"([^"]+)"', text, re.MULTILINE)
    if not match:
        raise SystemExit(f"[overview] cannot read version from {VERSION_PATH}")
    return match.group(1)


def test_count() -> int:
    suite = unittest.TestLoader().discover(
        str(ROOT / "tests"), pattern="test_pure_rag.py", top_level_dir=str(ROOT)
    )
    return suite.countTestCases()


def answer_recall(layers: Dict[str, Any]) -> float:
    answer_buckets = [layers[name] for name in ANSWER_LAYERS if name in layers]
    total = sum(int(bucket["answer_count"]) for bucket in answer_buckets)
    if total <= 0:
        raise SystemExit("[overview] evaluation report has no answer-layer items")
    return sum(int(bucket["hits"]) for bucket in answer_buckets) / total


def layer_rows(layers: Dict[str, Any]) -> List[Dict[str, Any]]:
    rows = []
    for key, label in LAYER_LABELS.items():
        bucket = layers.get(key)
        if bucket is None:
            raise SystemExit(f"[overview] evaluation report is missing layer {key}")
        answerable = int(bucket["answer_count"]) > 0
        rows.append(
            {
                "name": label,
                "count": int(bucket["count"]),
                "recall": float(bucket["recall"]) if answerable else None,
                "mrr": float(bucket["mrr"]) if answerable else None,
                "refusal": None if key in ANSWER_LAYERS else float(bucket["refusal_rate"]),
            }
        )
    return rows


def ablation_rows(payload: Dict[str, Any]) -> List[List[Any]]:
    rows = []
    for index, item in enumerate(payload.get("results", [])):
        metrics = item.get("metrics", {})
        if index >= len(ABLATION_LABELS):
            label = f"Configuration {index + 1}"
        else:
            label = ABLATION_LABELS[index]
        rows.append(
            [
                label,
                float(metrics["recall_at_k"]),
                float(metrics["mrr"]),
                float(metrics["rewrite_recall"]),
                float(metrics["case_recall"]),
            ]
        )
    if not rows:
        raise SystemExit("[overview] ablation report has no result rows")
    return rows


def alpha_rows(payload: Dict[str, Any]) -> List[List[Any]]:
    rows = []
    for item in payload.get("alpha_sweep", []):
        config = item.get("config", {})
        alpha = config.get("alpha")
        label = "adaptive" if alpha is None else f"{float(alpha):.1f}"
        metrics = item.get("metrics", {})
        rows.append(
            [
                label,
                float(metrics["recall_at_k"]),
                float(metrics["mrr"]),
                float(metrics["case_recall"]),
            ]
        )
    if not rows:
        raise SystemExit("[overview] ablation report has no alpha sweep rows")
    return rows


def collect_data() -> Dict[str, Any]:
    meta = load_json(META_PATH)
    report = load_json(REPORT_PATH)
    ablation = load_json(ABLATION_PATH)
    report_layers = report["layers"]["layers"]
    dataset_total = int(report["layers"]["dataset"]["total"])
    layer_total = sum(int(bucket["count"]) for bucket in report_layers.values())
    if dataset_total != layer_total:
        raise SystemExit(
            f"[overview] evaluation totals disagree: dataset={dataset_total}, layers={layer_total}"
        )
    return {
        "version": read_version(),
        "corpus_docs": int(meta["source_count"]),
        "chunks": int(meta["chunk_count"]),
        "answer_recall": answer_recall(report_layers),
        "eval_items": dataset_total,
        "eval_layers": len(report["dataset"]),
        "unit_tests": test_count(),
        "human_recall": float(report_layers["human_like"]["recall"]),
        "layers": layer_rows(report_layers),
        "ablation": ablation_rows(ablation),
        "alpha": alpha_rows(ablation),
    }


def render(data: Dict[str, Any]) -> str:
    json_text = json.dumps(data, ensure_ascii=True, indent=2)
    json_lines = json_text.splitlines()
    indented = "\n".join(f"  {line}" for line in json_lines[1:])
    return (
        f"{BEGIN_MARKER}\n"
        "(function () {\n"
        '  "use strict";\n'
        f"  window.WD_OVERVIEW_DATA = {json_lines[0]}\n{indented};\n"
        "})();\n"
        f"{END_MARKER}\n"
    )


def main(argv: List[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate or check project overview data")
    parser.add_argument("--check", action="store_true", help="fail when the generated asset drifts")
    args = parser.parse_args(argv)

    expected = render(collect_data())
    if args.check:
        if not OUTPUT_PATH.exists():
            print(f"[overview] missing generated asset {OUTPUT_PATH}")
            return 1
        actual = OUTPUT_PATH.read_text(encoding="utf-8")
        if actual == expected:
            print("[overview] generated asset matches the real sources")
            return 0
        print("[overview] generated asset drifted; run `python scripts/visualization/generate_overview.py`")
        return 1

    OUTPUT_PATH.write_text(expected, encoding="utf-8")
    print(f"[overview] wrote {OUTPUT_PATH}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
