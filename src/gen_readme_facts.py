"""
README 事实块生成器（仅标准库）

README 里能算出来的数字（语料规模、评测条数、指标、测试项数）不写死，
由本脚本从真源读取后写入 README 的 AUTO:FACTS 标记块：

- data/pure_index/report.json   `python src/rag_cli.py eval --report` 的输出
- data/pure_index/meta.json     索引元信息（报告缺失时用于交叉校验）
- data/knowledge_graph.json     图谱节点/边数
- tests/                        unittest 发现后的用例总数
- pure_rag.__version__          内核版本号

用法：
    python src/gen_readme_facts.py            # 写入 README.md
    python src/gen_readme_facts.py --check     # 只校验是否漂移，漂移则以非零码退出

语料或评测变化后（重建索引、重跑评测）都要重跑一次本脚本。
"""

import argparse
import json
import sys
import unittest
from pathlib import Path
from typing import Dict, List

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

BEGIN_MARKER = "<!-- BEGIN AUTO:FACTS (generated by: python src/gen_readme_facts.py) -->"
END_MARKER = "<!-- END AUTO:FACTS -->"

ANSWER_LAYERS = ("qa_verbatim", "qa_rewrite", "fault_case", "doc_title")


def _load_json(path: Path) -> Dict:
    """读取 JSON，缺失时给出可执行的修复命令（不做静默兜底）"""
    if not path.exists():
        raise SystemExit(f"[facts] 缺少真源文件 {path}，请先运行：python src/rag_cli.py eval --report")
    with open(path, "r", encoding="utf-8") as handle:
        return json.load(handle)


def _edge_count(graph: Dict) -> int:
    """边数：data/knowledge_graph.json 存的是边列表，内存里的图谱是邻接表，两种都算得出"""
    edges = graph.get("edges", [])
    if isinstance(edges, dict):
        return sum(len(value) for value in edges.values())
    return len(edges)


def collect_facts() -> Dict[str, object]:
    """从各真源汇总事实"""
    report = _load_json(ROOT / "data" / "pure_index" / "report.json")
    meta = _load_json(ROOT / "data" / "pure_index" / "meta.json")
    graph = _load_json(ROOT / "data" / "knowledge_graph.json")

    layers = report["layers"]["layers"]
    answers = sum(bucket["answer_count"] for name, bucket in layers.items()
                  if name in ANSWER_LAYERS) or 1
    answer_recall = sum(bucket["hits"] for name, bucket in layers.items()
                        if name in ANSWER_LAYERS) / answers

    loader = unittest.TestLoader()
    suite = loader.discover(str(ROOT / "tests"), pattern="test_*.py")

    from pure_rag import __version__

    return {
        "version": __version__,
        "documents": int(meta["source_count"]),
        "chunks": int(meta["chunk_count"]),
        "vocabulary": int(report["stats"]["vocabulary"]),
        "discovered_terms": int(report["stats"]["discovered_terms"]),
        "kg_nodes": len(graph.get("nodes", [])),
        "kg_edges": _edge_count(graph),
        "eval_total": int(report["layers"]["dataset"]["total"]),
        "eval_layers": len(report["dataset"]),
        "answer_recall": answer_recall,
        "human_recall": layers.get("human_like", {}).get("recall", 0.0),
        "human_count": layers.get("human_like", {}).get("count", 0),
        "near_miss_refusal": layers.get("near_miss", {}).get("refusal_rate", 0.0),
        "ood_refusal": layers.get("negative_ood", {}).get("refusal_rate", 0.0),
        "tests": suite.countTestCases(),
    }


def render_block(facts: Dict[str, object], lang: str = "zh") -> List[str]:
    """
    渲染成 Markdown 表格块

    只写「跨机器可复现」的事实：版本、语料规模、图谱规模、评测条数与指标、测试项数。
    Python 补丁版号、报告生成时间、查询耗时这类跟机器/时间走的数值不进 README，
    否则 CI 上的 `--check` 永远对不上；它们看 `data/pure_index/report.md` 即可。

    lang 为 "en" 时表头与标签走英文（用于 README.md 主版），其余走中文（用于 README.zh-CN.md）。
    """
    if lang == "en":
        return [
            BEGIN_MARKER,
            "",
            "| Item | Value | Source |",
            "|---|---|---|",
            f"| Kernel version | {facts['version']} | `pure_rag.__version__` |",
            f"| Corpus | {facts['documents']} docs / {facts['chunks']} chunks / vocab {facts['vocabulary']} "
            f"({facts['discovered_terms']} discovered) | `data/pure_index/meta.json` |",
            f"| Knowledge graph | {facts['kg_nodes']} nodes / {facts['kg_edges']} edges | `data/knowledge_graph.json` |",
            f"| Eval set | {facts['eval_total']} items ({facts['eval_layers']} layers) | `data/eval_set.json` |",
            f"| Answer-layer Recall@3 | {facts['answer_recall']:.2%} | `python src/rag_cli.py eval --report` |",
            f"| Colloquial-layer Recall@3 | {facts['human_recall']:.2%} ({facts['human_count']} items) | same |",
            f"| Near-miss refusal | {facts['near_miss_refusal']:.2%} | same |",
            f"| Out-of-domain refusal | {facts['ood_refusal']:.2%} | same |",
            f"| Unit tests | {facts['tests']} | `python -m unittest tests.test_pure_rag` |",
            "",
            END_MARKER,
        ]
    return [
        BEGIN_MARKER,
        "",
        "| 项 | 值 | 真源 |",
        "|---|---|---|",
        f"| 内核版本 | {facts['version']} | `pure_rag.__version__` |",
        f"| 语料规模 | {facts['documents']} 篇 / {facts['chunks']} 分块 / 词表 {facts['vocabulary']} 词 "
        f"（新词发现 {facts['discovered_terms']} 个） | `data/pure_index/meta.json` |",
        f"| 知识图谱 | {facts['kg_nodes']} 节点 / {facts['kg_edges']} 边 | `data/knowledge_graph.json` |",
        f"| 评测集 | {facts['eval_total']} 条（{facts['eval_layers']} 层） | `data/eval_set.json` |",
        f"| 回答层 Recall@3 | {facts['answer_recall']:.2%} | `python src/rag_cli.py eval --report` |",
        f"| 口语化层 Recall@3 | {facts['human_recall']:.2%}（{facts['human_count']} 条） | 同上 |",
        f"| 近邻负例拒答 | {facts['near_miss_refusal']:.2%} | 同上 |",
        f"| 域外问题拒答 | {facts['ood_refusal']:.2%} | 同上 |",
        f"| 单元测试 | {facts['tests']} 项 | `python -m unittest tests.test_pure_rag` |",
        "",
        END_MARKER,
    ]


def splice(readme_lines: List[str], block: List[str]) -> List[str]:
    """把事实块替换进 README 的标记区间；标记缺失时明确报错，不静默追加"""
    if BEGIN_MARKER not in readme_lines or END_MARKER not in readme_lines:
        raise SystemExit("[facts] README.md 缺少 AUTO:FACTS 标记，请先在目标位置写入起止标记行")
    start = readme_lines.index(BEGIN_MARKER)
    end = readme_lines.index(END_MARKER, start)
    return readme_lines[:start] + block + readme_lines[end + 1:]


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description="生成/校验 README 事实块")
    parser.add_argument("--check", action="store_true",
                        help="只比较当前 README 与真源是否一致，不一致时以非零码退出")
    parser.add_argument("--readme", default="README.md", help="目标文档（默认 README.md）")
    args = parser.parse_args(argv)

    from pure_rag.stdio import configure_streams

    configure_streams()

    path = ROOT / args.readme
    lang = "zh" if "zh-CN" in Path(args.readme).name else "en"
    lines = path.read_text(encoding="utf-8").splitlines()
    block = render_block(collect_facts(), lang)
    updated = splice(lines, block)

    if args.check:
        if updated == lines:
            print("[facts] README 事实块与真源一致")
            return 0
        print("[facts] README 事实块已漂移，请重跑：python src/gen_readme_facts.py")
        return 1

    path.write_text("\n".join(updated) + "\n", encoding="utf-8")
    print(f"[facts] 已写入 {path}（{len(block) - 2} 行事实块）")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
